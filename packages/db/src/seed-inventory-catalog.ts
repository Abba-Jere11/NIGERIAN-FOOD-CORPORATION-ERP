/**
 * Development-only inventory catalogue. Codes are unique per entity and stable
 * across re-runs so the seed stays idempotent.
 */

export type Track = 'none' | 'batch_lot' | 'serial';
export type StockStatus = 'AVAILABLE' | 'QUARANTINED' | 'REJECTED';
export type WarehouseKind = 'store' | 'cold_room' | 'yard' | 'plant';
export type AssetCondition = 'new' | 'good' | 'fair' | 'poor' | 'damaged';
export type AssetStatus = 'IN_STORE' | 'IN_SERVICE' | 'DISPOSAL_PENDING' | 'DISPOSED';

export interface WarehouseDef {
  code: string;
  name: string;
  kind: WarehouseKind;
  locations: Array<{ code: string; name: string }>;
}

export interface BatchDef {
  code: string;
  qty: number;
  status: StockStatus;
  /** Encoded into the batch code / movement notes — the table has no expiry column. */
  manufacturedOn: string;
  expiresOn: string | null;
}

export interface ItemDef {
  code: string;
  name: string;
  category: string;
  uom: string;
  reorder: number;
  tracking: Track;
  asset?: boolean;
  warehouse: string;
  location?: string;
  unitCostKobo: number;
  available?: number;
  quarantined?: number;
  rejected?: number;
  batches?: BatchDef[];
  /** Individually tracked units (serial + AST). */
  serialCount?: number;
  zero?: boolean;
}

export interface EntityCatalogue {
  code: string;
  categories: Array<{ key: string; name: string }>;
  warehouses: WarehouseDef[];
  items: ItemDef[];
}

const LOC = (prefix: string, n = 4): Array<{ code: string; name: string }> =>
  Array.from({ length: n }, (_, i) => {
    const aisle = String.fromCharCode(65 + (i % 4));
    const rack = String((i % 6) + 1).padStart(2, '0');
    return { code: `${prefix}-${aisle}${rack}`, name: `Aisle ${aisle} rack ${rack}` };
  });

function spare(
  prefix: string,
  warehouse: string,
  names: string[],
  unitCost: number,
  qty: number,
  reorder: number,
): ItemDef[] {
  return names.map((name, index) => ({
    code: `${prefix}-SP-${String(index + 1).padStart(3, '0')}`,
    name,
    category: 'spare_parts',
    uom: 'PCS',
    reorder,
    tracking: 'none',
    warehouse,
    unitCostKobo: unitCost + index * 2500,
    available: index % 7 === 0 ? Math.max(1, Math.floor(reorder / 2)) : qty + index,
    zero: index === names.length - 1,
  }));
}

function consumable(
  prefix: string,
  category: string,
  warehouse: string,
  uom: string,
  rows: Array<[string, string, number, number, number]>,
): ItemDef[] {
  return rows.map(([code, name, reorder, qty, kobo]) => ({
    code: `${prefix}-${code}`,
    name,
    category,
    uom,
    reorder,
    tracking: 'none',
    warehouse,
    unitCostKobo: kobo,
    available: qty,
  }));
}

